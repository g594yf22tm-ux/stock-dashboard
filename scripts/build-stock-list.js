function fetchPage(page) {
  return new Promise((resolve) => {
    const url = 'http://vip.stock.finance.sina.com.cn/quotes_service/api/json_v2.php/Market_Center.getHQNodeData?page='+page+'&num=80&sort=symbol&asc=1&node=hs_a&symbol=';
    http.get(url, {headers:{'User-Agent':'Mozilla/5.0','Referer':'https://finance.sina.com.cn/'}}, res => {
      let d=[];res.on('data',c=>d.push(c));res.on('end',()=>{
        try{
          const t=iconv.decode(Buffer.concat(d),'gbk');
          resolve(JSON.parse(t).map(s=>{
            const r=s.symbol||'';
            return {c:r.startsWith('sh')?r.replace('sh','')+'.SS':r.replace('sz','')+'.SZ',n:s.name};
          }));
        }catch{resolve([])}
      });
    }).on('error',()=>resolve([]));
  });
}

